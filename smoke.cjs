// Integrationstest mit eigener Benutzerdatenablage und synthetischem Testton.
const { app, BrowserWindow, dialog } = require('electron');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const testDirectory = path.join(__dirname, '.smoke-data');
app.setPath('userData', testDirectory);
require('./main.cjs');
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const deadline = setTimeout(() => { console.error('FAIL: Test-Zeitlimit'); app.exit(1); }, 45000);
app.whenReady().then(async () => {
  try {
    const win = BrowserWindow.getAllWindows()[0];
    const errors = [];
    win.webContents.on('console-message', (_event, details) => { if (details.level === 'error') errors.push(details.message); });
    if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    await delay(700);
    const js = script => win.webContents.executeJavaScript(script, true);
    assert.equal(await js('document.querySelectorAll(".cue").length'), 6);
    assert.equal(await js('Boolean(window.theater)'), true);
    await js(`$('addCue').click(); $('cueTitle').value='Integrationstest'; $('cueTitle').dispatchEvent(new Event('input'));`);
    assert.equal(await js('currentCue().title'), 'Integrationstest');
    await fs.mkdir(testDirectory, { recursive: true });
    const sampleCount = 44100 * 4;
    const wav = Buffer.alloc(44 + sampleCount * 2);
    wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
    wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
    wav.writeUInt32LE(44100, 24); wav.writeUInt32LE(88200, 28); wav.writeUInt16LE(2, 32);
    wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(sampleCount * 2, 40);
    for (let i = 0; i < sampleCount; i++) wav.writeInt16LE(Math.round(Math.sin(i * 440 * 2 * Math.PI / 44100) * 200), 44 + i * 2);
    const audioFile = path.join(testDirectory, 'test.wav');
    await fs.writeFile(audioFile, wav);
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [audioFile] });
    await js('pickFiles(true)');
    await js(`updateCue('behavior','pause'); trigger(currentCue())`);
    await delay(200);
    assert.equal(await js('runtime(selected).state'), 'playing');
    await js('trigger(currentCue())');
    assert.equal(await js('runtime(selected).state'), 'paused');
    const pausedTime = await js('runtime(selected).audio.currentTime');
    assert.ok(pausedTime > 0);
    await js('trigger(currentCue())');
    assert.equal(await js('runtime(selected).state'), 'playing');
    assert.ok(await js('runtime(selected).audio.currentTime') >= pausedTime);
    await js(`updateCue('gain',-6)`);
    await delay(200);
    assert.ok(Math.abs(await js('runtime(selected).gainNode.gain.value') - Math.pow(10, -6 / 20)) < .01);
    await js(`updateCue('behavior','stop'); trigger(currentCue())`);
    assert.equal(await js('runtime(selected).state'), 'idle');
    assert.equal(await js('runtime(selected).audio.currentTime'), 0);
    await js('trigger(currentCue());');
    await js(`document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`);
    assert.equal(await js('runtime(selected).state'), 'idle');
    await js(`$('cueNotes').focus(); $('cueNotes').dispatchEvent(new KeyboardEvent('keydown',{code:'Space',bubbles:true}));`);
    assert.equal(await js('runtime(selected).state'), 'idle');
    await js(`$('cueNotes').blur(); $('modeButton').click();`);
    assert.equal(await js('$(' + JSON.stringify('cueTitle') + ').disabled'), true);
    await js(`$('modeButton').click();`);
    const output = path.join(testDirectory, 'export.theater.json');
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: output });
    await js('saveProject(true)');
    const exported = JSON.parse(await fs.readFile(output, 'utf8'));
    const savedCue = exported.cues.find(cue => cue.title === 'Integrationstest');
    assert.ok(savedCue.path && !path.isAbsolute(savedCue.path));
    await fs.access(path.join(testDirectory, savedCue.path));
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [output] });
    await js(`(async()=>{ const data=await window.theater.openProject(); loadProject(data); choose(project.cues.find(c=>c.title==='Integrationstest').id); await trigger(currentCue()); })()`);
    assert.equal(await js('runtime(selected).state'), 'playing');
    await js('stopAll()');
    // Ein neuer Start beendet andere Einsätze, wenn Überlagerung deaktiviert ist.
    await js(`$('addCue').click();`);
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [audioFile] });
    await js('pickFiles(true);');
    await js('trigger(currentCue())');
    await js(`choose(project.cues.find(c=>c.title==='Integrationstest').id); project.overlap=false; trigger(currentCue())`);
    assert.equal(await js(`[...runtimes.values()].filter(r=>r.state==='playing').length`), 1);
    await js(`project.overlap=true; choose(project.cues[project.cues.length-1].id); trigger(currentCue())`);
    assert.equal(await js(`[...runtimes.values()].filter(r=>r.state==='playing').length`), 2);
    await js('stopAll()');
    // Klickmodus: Auswahl allein startet nicht; Direktmodus startet und stoppt.
    await js(`project.clickMode='select'; document.querySelector('.cue:last-child').click();`);
    assert.equal(await js('runtime(selected).state'), 'idle');
    await js(`project.clickMode='direct'; document.querySelector('.cue:last-child').click();`);
    await delay(150);
    assert.equal(await js('runtime(selected).state'), 'playing');
    await js(`document.querySelector('.cue:last-child').click();`);
    assert.equal(await js('runtime(selected).state'), 'idle');
    await js(`demo();`);
    await js(`clearTimeout(toastTimer); $('toast').style.display='none';`);
    await delay(400);
    const image = await win.webContents.capturePage();
    await fs.writeFile(path.join(__dirname, 'preview.png'), image.toPNG());
    assert.deepEqual(errors, []);
    console.log('PASS: Kacheln, Bearbeitung, Audiodatei, Wiedergabe, Pause/Fortsetzen, Stopp/Neustart, Gain, Escape, Eingabeschutz, Aufführungsmodus, Audioexport, Wiederöffnung, Überlagerung und Klickmodi.');
    clearTimeout(deadline); app.exit(0);
  } catch (error) { console.error(error); clearTimeout(deadline); app.exit(1); }
});
